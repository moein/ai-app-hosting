// Bundles src/cli.ts into a single dependency-free ESM script and stores it as a string module the api serves
// at /v1/contract/validator/<version>.mjs. Run after changing the validator: pnpm -F @repo/app-contract build:validator
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
export const OUTPUT = `${root}src/validator-bundle.generated.ts`;

export async function bundleValidator() {
  const result = await build({
    entryPoints: [`${root}src/cli.ts`],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    write: false,
    legalComments: 'none',
  });
  return result.outputFiles[0].text;
}

export const generateBundleModule = (code) =>
  `// Generated by scripts/build-validator.mjs from src/cli.ts — do not edit by hand.\nexport const VALIDATOR_BUNDLE = ${JSON.stringify(code)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateBundleModule(await bundleValidator()));
  process.stdout.write(`wrote ${OUTPUT}\n`);
}
